const SLOT_INDEX: ReadonlyMap<string, BuiltinParamSlot> = new Map(
  BUILTIN_PARAM_SLOTS.map((s) => [slotKey(s.ownerKind, s.owner, s.kind, s.aceId, s.paramId), s]),
);

function slotKey(ownerKind: string, owner: string, kind: string, aceId: string, paramId: string): string {
  return JSON.stringify([ownerKind, owner, kind, aceId, paramId]);
}

/** Look up the boolean slot for a built-in ACE parameter by its full tuple. */
export function builtinParamSlot(
  ownerKind: BuiltinParamOwnerKind,
  owner: string,
  kind: BuiltinParamAceKind,
  aceId: string,
  paramId: string,
): BuiltinParamSlot | undefined {
  return SLOT_INDEX.get(slotKey(ownerKind, owner, kind, aceId, paramId));
}

/** The owner kinds that have at least one row. */
export function builtinParamOwnerKinds(): BuiltinParamOwnerKind[] {
  return [...new Set(BUILTIN_PARAM_SLOTS.map((s) => s.ownerKind))];
}
