/**
 * Built-in ACE parameters that the C3 editor loads as booleans, as a lookup table.
 *
 * Provenance: a capture of C3 editor release r495-2. The data was read from
 * `plugins/allAces.json`, `behaviors/allAces.json` and the common ACE registrations
 * in `main.js`. It was read, not run. Captured 2026-11-10. sha256 of the sources:
 *   - main.js                18c7a7cee194779da60deba01052a74ae57b8c038eadd0041932ced68794d10c
 *   - projectResources.js    e0180c2a41e4f8103e2a6b5a5ab6e8be7eb3d1e97e331b2b18de2969d60b7b43
 *   - plugins/allAces.json   5ad106361687501e583cb2825ac09aef707b306087b92862c1688937ce69ae7b
 *   - behaviors/allAces.json 36a6466649a2070526ca58431f7ac00e27fd3dd8761d44ff840285fb142e20d1
 *
 * This is a local bridge until GenvidTechnologies/c3source#132 ships the table.
 * The tripwire test `I371-T1:` goes red when c3source exports it.
 *
 * `paramType: "boolean"` means the editor loads the value with `!!`, so only a native
 * true/false survives. `paramType: "combo-bool"` means a choice whose items are exactly
 * the strings "false" and "true": a native boolean there throws at editor load, and any
 * other string falls back to the initial value.
 *
 * An ACE id is not unique across owners (for example `set-enabled` is boolean on some
 * behaviors and a `["disabled", "enabled"]` combo elsewhere), so rows are keyed by the
 * full tuple (ownerKind, owner, kind, aceId, paramId).
 */

