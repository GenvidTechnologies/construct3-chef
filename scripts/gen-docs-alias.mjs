#!/usr/bin/env node
// Generates a flat `docs/` alias from `wiki/`, for the published npm tarball
// ONLY (wired through `prepack`/`postpack`, never committed to the working
// tree — see .gitignore).
//
// `exposeDocs` (upstream @genvidtech/mcp-utils) hardcodes a flat,
// non-recursive scan of `<packageDir>/docs`. `docs/` was retired into
// `wiki/` by ADR 0028, so the MCP `docs:///{name}` resource has served
// nothing since that consolidation. This script rebuilds the flat surface
// `exposeDocs` expects, at pack time, from the wiki bundle it can no longer
// see directly.
//
//   node scripts/gen-docs-alias.mjs           # write docs/
//   node scripts/gen-docs-alias.mjs --clean   # remove the generated docs/
//   node scripts/gen-docs-alias.mjs --check   # exit 1 if docs/ is stale
//
// See wiki/decisions/0029-*.

import { readFileSync, writeFileSync, readdirSync, statSync, existsSync, mkdirSync, rmSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { SECTIONS, RESERVED, resolveWikiDir } from "./gen-wiki-index.mjs";

const REPO_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

export function resolveDocsDir(repoRoot = REPO_ROOT) {
  return path.join(repoRoot, "docs");
}

/**
 * Collect every wiki page eligible for the flat alias: the bundle root's own
 * `*.md` files plus each `SECTIONS` directory's `*.md` files, excluding
 * anything matching `RESERVED` (index.md / log.md at every level — the same
 * exclusion `gen-wiki-index.mjs` and the OKF conformance walk use).
 *
 * Returns an array of `{ stem, abs, section }`, `section` being the
 * `SECTIONS` key or `null` for a bundle-root page. Does not check for stem
 * collisions — that's `buildDocsAlias`'s job.
 */
export function collectSourcePages(repoRoot = REPO_ROOT) {
  const wikiDir = resolveWikiDir(repoRoot);
  const absWiki = path.join(repoRoot, wikiDir);
  const pages = [];

  const addDir = (absDir, section) => {
    if (!existsSync(absDir)) return;
    for (const f of readdirSync(absDir).sort()) {
      if (!f.endsWith(".md") || RESERVED.test(f)) continue;
      const abs = path.join(absDir, f);
      if (!statSync(abs).isFile()) continue;
      pages.push({ stem: f.slice(0, -3), abs, section });
    }
  };

  addDir(absWiki, null);
  for (const dir of Object.keys(SECTIONS)) {
    addDir(path.join(absWiki, dir), dir);
  }

  return pages;
}

function buildManifest(pages) {
  const bySection = new Map();
  for (const p of pages) {
    const key = p.section ?? "__root__";
    if (!bySection.has(key)) bySection.set(key, []);
    bySection.get(key).push(p.stem);
  }
  for (const arr of bySection.values()) arr.sort();

  const lines = [
    "# Generated docs alias index",
    "",
    "This file is generated by `scripts/gen-docs-alias.mjs` at pack time from",
    "`wiki/`. Do not hand-edit it — it exists only inside the published npm",
    "tarball, never in the working tree. Each page below is addressed by the",
    "MCP `docs:///{name}` resource using the name shown (no `.md` extension,",
    "no path segments).",
    "",
  ];

  const emitList = (stems) => {
    for (const stem of stems) lines.push(`* \`docs:///${stem}\``);
    lines.push("");
  };

  if (bySection.has("__root__")) {
    lines.push("## Top-level");
    lines.push("");
    emitList(bySection.get("__root__"));
  }

  for (const [dir, [title]] of Object.entries(SECTIONS)) {
    if (!bySection.has(dir)) continue;
    lines.push(`## ${title}`);
    lines.push("");
    emitList(bySection.get(dir));
  }

  return lines.join("\n").replace(/\n+$/, "\n");
}

/**
 * Build the full set of files the alias should contain: a verbatim byte
 * copy of every collected page at `docs/<stem>.md`, plus a generated
 * `docs/index.md` manifest. Throws on any stem collision, naming both
 * source paths, rather than silently overwriting.
 *
 * Returns a Map of repo-relative path ("docs/<name>.md") -> Buffer.
 */
export function buildDocsAlias(repoRoot = REPO_ROOT) {
  const pages = collectSourcePages(repoRoot);

  const byStem = new Map();
  for (const p of pages) {
    const existing = byStem.get(p.stem);
    if (existing) {
      throw new Error(`gen-docs-alias: stem collision for "${p.stem}" between ${existing.abs} and ${p.abs}`);
    }
    byStem.set(p.stem, p);
  }

  // Guard rather than silently overwrite, though RESERVED already excludes
  // index.md from `pages` — this only fires if that exclusion ever changes.
  if (byStem.has("index")) {
    const clash = byStem.get("index");
    throw new Error(`gen-docs-alias: page ${clash.abs} would collide with the generated docs/index.md manifest`);
  }

  const files = new Map();
  for (const p of byStem.values()) {
    files.set(`docs/${p.stem}.md`, readFileSync(p.abs));
  }
  files.set("docs/index.md", Buffer.from(buildManifest(pages), "utf8"));

  return files;
}

export function generate(repoRoot = REPO_ROOT) {
  const files = buildDocsAlias(repoRoot);
  mkdirSync(resolveDocsDir(repoRoot), { recursive: true });
  for (const [rel, content] of files) {
    writeFileSync(path.join(repoRoot, rel), content);
  }
  return files;
}

export function clean(repoRoot = REPO_ROOT) {
  rmSync(resolveDocsDir(repoRoot), { recursive: true, force: true });
}

/** Returns an array of human-readable diff lines; empty means up to date. */
export function check(repoRoot = REPO_ROOT) {
  const files = buildDocsAlias(repoRoot);
  const docsDir = resolveDocsDir(repoRoot);
  const diffs = [];

  const expectedNames = new Set([...files.keys()].map((rel) => path.basename(rel)));
  const existingNames = existsSync(docsDir) ? readdirSync(docsDir).filter((f) => f.endsWith(".md")) : [];

  for (const name of existingNames) {
    if (!expectedNames.has(name)) diffs.push(`extra: docs/${name}`);
  }

  for (const [rel, content] of files) {
    const abs = path.join(repoRoot, rel);
    if (!existsSync(abs)) {
      diffs.push(`missing: ${rel}`);
      continue;
    }
    if (!readFileSync(abs).equals(content)) diffs.push(`differs: ${rel}`);
  }

  return diffs;
}

function main() {
  const args = process.argv.slice(2);

  if (args.includes("--clean")) {
    const existed = existsSync(resolveDocsDir());
    clean();
    console.log(existed ? "removed docs/ (generated alias)" : "docs/ already absent, nothing to remove");
    return;
  }

  if (args.includes("--check")) {
    const diffs = check();
    if (diffs.length) {
      console.error(`docs/ alias is stale (run \`npm run docs:alias\`):\n  ${diffs.join("\n  ")}`);
      process.exitCode = 1;
    } else {
      console.log("docs/ alias up to date");
    }
    return;
  }

  const files = generate();
  console.log(`wrote ${files.size} files to docs/`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
